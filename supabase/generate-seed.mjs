/* Regenerate supabase/seed.sql from the storefront's bundled demo data.
   Usage: node supabase/generate-seed.mjs   (from the fashion-mall folder) */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const storePath = path.join(here, '..', 'assets', 'js', 'store.js');
const outPath = path.join(here, 'seed.sql');

const storage = new Map();
const localStorage = {
  getItem: (key) => (storage.has(key) ? storage.get(key) : null),
  setItem: (key, value) => storage.set(key, String(value)),
  removeItem: (key) => storage.delete(key)
};
const document = { dispatchEvent() {} };
const window = {};
class CustomEvent {
  constructor(type, init) { this.type = type; this.detail = init && init.detail; }
}

const source = fs.readFileSync(storePath, 'utf8');
new Function('window', 'localStorage', 'document', 'CustomEvent', source)(
  window, localStorage, document, CustomEvent
);

const state = window.ECRU.state();

const q = (value) => (value == null ? 'null' : `$tl$${String(value).replaceAll('$tl$', '$ tl$')}$tl$`);
const json = (value) => `${q(JSON.stringify(value ?? null))}::jsonb`;
const arr = (values) => (Array.isArray(values) && values.length
  ? `array[${values.map((v) => q(v)).join(', ')}]::text[]`
  : `'{}'::text[]`);
const bool = (value) => (value ? 'true' : 'false');
const num = (value) => Number(value) || 0;

const lines = [];
lines.push('-- To Lead — demo seed data');
lines.push('-- Generated by supabase/generate-seed.mjs from assets/js/store.js.');
lines.push('-- Run after schema.sql. Safe to re-run: conflicts are ignored.');
lines.push('');

lines.push('-- Products');
state.products.forEach((p) => {
  lines.push(`insert into public.products (id, sku, name, gender, type, price, compare_at, image, colors, sizes, stock, rating, review_count, badge, is_new, description, details, composition, fit, created_at) values (`
    + `${q(p.id)}, ${q(p.sku)}, ${q(p.name)}, ${q(p.gender)}, ${q(p.type)}, ${num(p.price)}, ${p.compareAt == null ? 'null' : num(p.compareAt)}, ${q(p.image)}, ${json(p.colors)}, ${arr(p.sizes)}, ${num(p.stock)}, ${Number(p.rating) || 4.7}, ${num(p.reviewCount)}, ${p.badge == null ? 'null' : q(p.badge)}, ${bool(p.isNew)}, ${q(p.description)}, ${arr(p.details)}, ${q(p.composition)}, ${q(p.fit)}, ${q(p.createdAt)}::date) on conflict (id) do nothing;`);
});
lines.push('');

lines.push('-- Customers (totals are refreshed by the orders trigger)');
state.customers.forEach((c) => {
  lines.push(`insert into public.customers (id, name, email, joined, segment) values (`
    + `${q(c.id)}, ${q(c.name)}, ${q(c.email)}, ${q(c.joined)}::date, ${q(c.segment)}) on conflict do nothing;`);
});
lines.push('');

lines.push('-- Orders and line items');
const customerByEmail = new Map(state.customers.map((c) => [c.email, c]));
state.orders.forEach((o) => {
  const customer = customerByEmail.get(o.customer.email);
  lines.push(`insert into public.orders (id, customer_id, customer_name, customer_email, created_at, subtotal, shipping, total, status, payment, channel) values (`
    + `${q(o.id)}, ${customer ? q(customer.id) : 'null'}, ${q(o.customer.name)}, ${q(o.customer.email)}, ${q(o.date)}::timestamptz, ${num(o.subtotal)}, ${num(o.shipping)}, ${num(o.total)}, ${q(o.status)}, ${q(o.payment)}, ${q(o.channel)}) on conflict (id) do nothing;`);
  o.items.forEach((item) => {
    lines.push(`insert into public.order_items (order_id, product_id, name, size, qty, price) values (`
      + `${q(o.id)}, ${q(item.productId)}, ${q(item.name)}, ${q(item.size)}, ${num(item.qty)}, ${num(item.price)}) on conflict do nothing;`);
  });
});
lines.push('');

lines.push('-- Storefront content');
lines.push(`insert into public.settings (id, data) values ('main', ${json(state.settings)}) on conflict (id) do nothing;`);
lines.push('');

lines.push('-- Newsletter subscribers');
state.subscribers.forEach((email) => {
  lines.push(`insert into public.subscribers (email) values (${q(email)}) on conflict (email) do nothing;`);
});
lines.push('');

lines.push('-- Recompute customer purchase history totals');
lines.push('select public.refresh_customer_totals(id) from public.customers;');
lines.push('');

fs.writeFileSync(outPath, lines.join('\n'), 'utf8');
console.log(`Wrote ${outPath}`);
console.log(`${state.products.length} products, ${state.customers.length} customers, ${state.orders.length} orders.`);
